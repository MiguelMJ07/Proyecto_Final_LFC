# ======================================================================= tables
_TEX = {"\\": r"\textbackslash{}", "{": r"\{", "}": r"\}", "$": r"\$", "&": r"\&", "#": r"\#", "%": r"\%",
        "_": r"\_", "^": r"\^{}", "~": r"\~{}", "<": r"\textless{}", ">": r"\textgreater{}", "|": r"\textbar{}",
        "[": "{[}", "]": "{]}", "-": "{-}", "'": r"\textquotesingle{}", "`": r"\textasciigrave{}"}


def tex(text):
    """Escapes every character that is special in LaTeX text mode ([ ] and - too: after \\\\ or doubled they change
    meaning)."""
    return "".join(_TEX.get(ch, ch) for ch in str(text))


class PlainCells:
    """Cell text for CSV: the same notation as the JSON answers (A -> aB, e, shift 5 / reduce A -> b / accept)."""

    def __init__(self, slr=None):
        self.slr = slr

    sym = staticmethod(str)
    prod = staticmethod(prod_str)
    set = staticmethod(fmt_set)

    def action(self, act):
        return self.slr._act_str(act)


class TexCells:
    """Cell text for LaTeX: book notation (A $\\to$ aB, $\\varepsilon$, s5 / r2 / acc), special characters escaped."""

    def __init__(self, slr=None):
        self.slr = slr

    sym = staticmethod(tex)

    @staticmethod
    def prod(head, body):
        h = "S$'$" if head == AUG else tex(head)
        return h + r" $\to$ " + ("".join(tex(x) for x in body) if body else r"$\varepsilon$")

    @staticmethod
    def set(items):
        ordered = sorted(x for x in items if x not in (EPS, END)) + [x for x in (EPS, END) if x in items]
        return r"\{" + ", ".join(r"$\varepsilon$" if x == EPS else tex(x) for x in ordered) + r"\}"

    @staticmethod
    def action(act):
        return "acc" if act[0] == "acc" else f"{act[0]}{act[1]}"


def sets_table(g, cells):
    return {"title": "FIRST and FOLLOW (Section 4.4.2)", "header": ["Nonterminal", "FIRST", "FOLLOW"],
            "rows": [[cells.sym(A), cells.set(g.first[A]), cells.set(g.follow[A])] for A in g.nonterminals]}


def ll1_table(g, ll, cells):
    """Rows: nonterminals; columns: terminals and $. A cell with more than one production is a conflict."""
    cols = g.terminals + [END]
    rows = [[cells.sym(A)] + [" / ".join(cells.prod(*g.prods[i]) for i in ll.table.get((A, a), [])) for a in cols]
            for A in g.nonterminals]
    return {"title": "LL(1) predictive parsing table M (Algorithm 4.31)",
            "header": ["Nonterminal"] + [cells.sym(a) for a in cols], "rows": rows}


def slr1_table(g, slr, cells):
    """ACTION columns (terminals and $) then GOTO columns (nonterminals). Conflicting actions share a cell."""
    tcols = g.terminals + [END]
    rows = []
    for s in range(len(slr.states)):
        action = [" / ".join(cells.action(c) for c in slr.action.get((s, a), [])) for a in tcols]
        goto = [str(slr.goto[(s, A)]) if (s, A) in slr.goto else "" for A in g.nonterminals]
        rows.append([str(s)] + action + goto)
    return {"title": "SLR(1) parsing table (Section 4.6.4)",
            "header": ["State"] + [cells.sym(a) for a in tcols] + [cells.sym(A) for A in g.nonterminals],
            "groups": [("", 1), ("ACTION", len(tcols)), ("GOTO", len(g.nonterminals))], "rows": rows}


def numbered_productions(slr, cells):
    """The numbering used by rN in the LaTeX SLR(1) table; production 0 is the augmented S' -> S."""
    return {"title": r"Productions of the augmented grammar (r$n$ reduces by production $n$)",
            "header": ["$n$", "Production"], "rows": [[str(p), cells.prod(h, b)] for p, (h, b) in enumerate(slr.aug)]}


def to_csv(table):
    """One table per CSV file. Grouped columns (ACTION / GOTO) are named like ACTION[a] and GOTO[A]."""
    header = table["header"]
    if table.get("groups"):
        labels = [label for label, span in table["groups"] for _ in range(span)]
        header = [f"{label}[{h}]" if label else h for label, h in zip(labels, header)]
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(header)
    w.writerows(table["rows"])
    return buf.getvalue()


def to_latex(tables, standalone=False):
    """tabular environments that need no extra package; `standalone` wraps them in a complete document."""
    out = ["% Generated by POST /grammar/export (format latex). No extra LaTeX packages are needed."]
    if standalone:
        out += [r"\documentclass{article}", r"\begin{document}"]
    for t in tables:
        n = len(t["header"])
        out += [r"\begin{table}[h]", r"\centering", r"\small", f"\\caption{{{t['title']}}}",
                r"\begin{tabular}{|" + "c|" * n + "}", r"\hline"]
        if t.get("groups"):
            spans = [f"\\multicolumn{{{span}}}{{{'|c|' if i == 0 else 'c|'}}}{{{label}}}"
                     for i, (label, span) in enumerate(t["groups"]) if span]
            out.append(" & ".join(spans) + r" \\ \hline")
        out.append(" & ".join(t["header"]) + r" \\ \hline")
        out += [" & ".join(row) + r" \\ \hline" for row in t["rows"]]
        out += [r"\end{tabular}", r"\end{table}", ""]
    if standalone:
        out.append(r"\end{document}")
    return "\n".join(out) + "\n"


# ======================================================================= drawings
def _dot_label(text):
    return str(text).replace("\\", "\\\\").replace('"', '\\"')


def tree_dot(root):
    """Graphviz source of a parse tree; children keep their order and an epsilon production gets an ε leaf."""
    lines = ["digraph tree {", "  ordering=out;", '  node [shape=plaintext, fontname="Helvetica"];',
             "  edge [arrowhead=none];"]
    for n in number_nodes(root):
        color = "#1e1b4b" if is_nt(n.symbol) else "#b45309"
        lines.append(f'  n{n.id} [label="{_dot_label(n.symbol)}", fontcolor="{color}"];')
        for c in n.children:
            lines.append(f"  n{n.id} -> n{c.id};")
        if n.prod is not None and not n.children:
            lines.append(f'  eps{n.id} [label="ε", fontcolor="#6b7280"];')
            lines.append(f"  n{n.id} -> eps{n.id};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def _num(v):
    return f"{v:.1f}".rstrip("0").rstrip(".")


def _svg(width, height, title, body, defs=""):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{_num(width)}" height="{_num(height)}" '
            f'viewBox="0 0 {_num(width)} {_num(height)}" font-family="Helvetica, Arial, sans-serif">\n'
            f"<title>{escape(title)}</title>\n{defs}"
            f'<rect width="100%" height="100%" fill="#ffffff"/>\n' + "\n".join(body) + "\n</svg>\n")


TREE_DX, TREE_DY, TREE_PAD = 38, 58, 28


def tree_svg(root, title="Parse tree"):
    """Leaves (and ε leaves) take consecutive columns from left to right; every internal node is centred over its
    children. Iterative, so deep trees do not hit Python's recursion limit."""
    nodes = number_nodes(root)                       # pre-order: leaves appear from left to right
    depth = {root.id: 0}
    for n in nodes:
        for c in n.children:
            depth[c.id] = depth[n.id] + 1
    x, slot = {}, 0
    for n in nodes:
        if not n.children:                           # a terminal, or a node for an epsilon production
            x[n.id] = slot
            slot += 1
    for n in reversed(nodes):                        # children before parents
        if n.children:
            x[n.id] = (x[n.children[0].id] + x[n.children[-1].id]) / 2
    eps = [n for n in nodes if n.prod is not None and not n.children]
    max_depth = max([depth[n.id] for n in nodes] + [depth[n.id] + 1 for n in eps])

    def px(n_id):
        return TREE_PAD + x[n_id] * TREE_DX

    def py(d):
        return TREE_PAD + d * TREE_DY

    edges, labels = [], []
    for n in nodes:
        for c in n.children:
            edges.append(f'<line x1="{_num(px(n.id))}" y1="{_num(py(depth[n.id]))}" x2="{_num(px(c.id))}" '
                         f'y2="{_num(py(depth[c.id]))}" stroke="#9ca3af" stroke-width="1.5"/>')
    for n in eps:
        edges.append(f'<line x1="{_num(px(n.id))}" y1="{_num(py(depth[n.id]))}" x2="{_num(px(n.id))}" '
                     f'y2="{_num(py(depth[n.id] + 1))}" stroke="#9ca3af" stroke-width="1.5"/>')
        labels.append(f'<text x="{_num(px(n.id))}" y="{_num(py(depth[n.id] + 1))}" text-anchor="middle" '
                      f'dominant-baseline="central" font-size="15" font-style="italic" fill="#6b7280">ε</text>')
    for n in nodes:
        cx, cy = _num(px(n.id)), _num(py(depth[n.id]))
        if is_nt(n.symbol):
            labels.append(f'<circle cx="{cx}" cy="{cy}" r="14" fill="#eef2ff" stroke="#4338ca" stroke-width="1.5"/>')
            labels.append(f'<text x="{cx}" y="{cy}" text-anchor="middle" dominant-baseline="central" font-size="15" '
                          f'fill="#1e1b4b">{escape(n.symbol)}</text>')
        else:
            labels.append(f'<rect x="{_num(px(n.id) - 12)}" y="{_num(py(depth[n.id]) - 12)}" width="24" height="24" '
                          f'rx="5" fill="#fffbeb" stroke="#d97706"/>')
            labels.append(f'<text x="{cx}" y="{cy}" text-anchor="middle" dominant-baseline="central" font-size="15" '
                          f'font-weight="bold" fill="#92400e">{escape(n.symbol)}</text>')
    width = 2 * TREE_PAD + max(slot - 1, 0) * TREE_DX
    height = 2 * TREE_PAD + max_depth * TREE_DY
    return _svg(width, height, title, edges + labels)


LR_CHAR, LR_LINE, LR_PAD = 7.4, 16, 8          # monospace 12px: width of a character, height of a line
LR_GAP_X, LR_GAP_Y, LR_MARGIN = 110, 46, 30
GOTOS_PER_LINE = 3
_ARROW = ('<defs><marker id="arrow" viewBox="0 0 10 10" refX="10" refY="5" markerWidth="7" markerHeight="7" '
          'orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 z" fill="#475569"/></marker></defs>\n')


def _edge_label(x, y, text):
    return (f'<text x="{_num(x)}" y="{_num(y)}" text-anchor="middle" font-size="13" fill="#1d4ed8" '
            f'stroke="#ffffff" stroke-width="4" paint-order="stroke">{escape(text)}</text>')


def lr0_svg(slr, title="LR(0) automaton"):
    """Canonical collection of LR(0) items. Column k holds the states at distance k from I0 (breadth-first), so an
    arrow is drawn for every transition into the next column and for every self-loop; those arrows stay in the
    gaps between columns and never cross a box. The remaining transitions (to the same or an earlier column) are
    written inside the box of their source as GOTO: X → In. The DOT output draws every transition as an edge."""
    edges = {}
    for (s, X), t in sorted(slr.trans.items()):
        edges.setdefault((s, t), []).append(X)
    depth, queue = {0: 0}, deque([0])
    while queue:
        s = queue.popleft()
        for (_, t) in sorted(k for k in edges if k[0] == s):
            if t not in depth:
                depth[t] = depth[s] + 1
                queue.append(t)
    columns = {}
    for s in sorted(depth):
        columns.setdefault(depth[s], []).append(s)
    drawn = {k for k in edges if k[0] == k[1] or depth[k[1]] == depth[k[0]] + 1}

    box = {}
    for s, I in enumerate(slr.states):
        gotos = [f"{X} → I{t}" for (u, t), syms in sorted(edges.items(), key=lambda e: e[1]) if u == s
                 and (u, t) not in drawn for X in syms]
        footer = ["GOTO: " + ", ".join(gotos[i:i + GOTOS_PER_LINE]) for i in range(0, len(gotos), GOTOS_PER_LINE)]
        items = [f"I{s}"] + [slr.item_str(p, d) for p, d in sorted(I)]
        lines = items + footer
        box[s] = {"items": items, "footer": footer, "w": max(len(t) for t in lines) * LR_CHAR + 2 * LR_PAD,
                  "h": len(lines) * LR_LINE + LR_PAD + (6 if footer else 0)}
    x_col, x, bottom = {}, LR_MARGIN + 24, 0          # room for the start arrow
    for d in sorted(columns):
        x_col[d] = x
        y = LR_MARGIN + 28                            # room for self-loops above the first box
        for s in columns[d]:
            box[s].update(x=x, y=y)
            y += box[s]["h"] + LR_GAP_Y
        bottom = max(bottom, y - LR_GAP_Y)
        x += max(box[s]["w"] for s in columns[d]) + LR_GAP_X

    body = []
    fan = {}
    for (s, t) in sorted(drawn):
        if s != t:
            fan.setdefault(s, []).append(t)
    for (s, t) in sorted(drawn):
        label, b, c = ", ".join(edges[(s, t)]), box[s], box[t]
        if s == t:                                    # self-loop over the top of the box
            cx = b["x"] + min(b["w"] / 2, 40)
            body.append(f'<path d="M{_num(cx - 9)},{_num(b["y"])} C{_num(cx - 22)},{_num(b["y"] - 30)} '
                        f'{_num(cx + 22)},{_num(b["y"] - 30)} {_num(cx + 9)},{_num(b["y"])}" fill="none" '
                        f'stroke="#475569" stroke-width="1.3" marker-end="url(#arrow)"/>')
            body.append(_edge_label(cx, b["y"] - 26, label))
            continue
        k = fan[s].index(t)                           # spread the arrows that leave the same box
        y1 = b["y"] + b["h"] * (k + 1) / (len(fan[s]) + 1)
        y2 = c["y"] + min(c["h"] / 2, 3 * LR_LINE)
        x1, x2 = b["x"] + b["w"], c["x"]
        body.append(f'<line x1="{_num(x1)}" y1="{_num(y1)}" x2="{_num(x2)}" y2="{_num(y2)}" '
                    f'stroke="#475569" stroke-width="1.3" marker-end="url(#arrow)"/>')
        body.append(_edge_label(x1 + (x2 - x1) * 0.3, y1 + (y2 - y1) * 0.3 - 4, label))

    accept = {s for s, I in enumerate(slr.states) if (0, 1) in I}     # contains S' -> S.
    for s in sorted(box):
        b = box[s]
        stroke = "#15803d" if s in accept else "#334155"
        body.append(f'<rect x="{_num(b["x"])}" y="{_num(b["y"])}" width="{_num(b["w"])}" height="{_num(b["h"])}" '
                    f'rx="6" fill="#f8fafc" stroke="{stroke}" stroke-width="{2.5 if s in accept else 1.3}"/>')
        for i, line in enumerate(b["items"]):
            weight = ' font-weight="bold"' if i == 0 else ""
            body.append(f'<text x="{_num(b["x"] + LR_PAD)}" y="{_num(b["y"] + LR_PAD / 2 + (i + 0.8) * LR_LINE)}" '
                        f'font-family="Menlo, Consolas, monospace" font-size="12" fill="#0f172a"{weight} '
                        f'xml:space="preserve">{escape(line)}</text>')
        if b["footer"]:
            sep = b["y"] + LR_PAD / 2 + len(b["items"]) * LR_LINE + 4
            body.append(f'<line x1="{_num(b["x"])}" y1="{_num(sep)}" x2="{_num(b["x"] + b["w"])}" y2="{_num(sep)}" '
                        f'stroke="#cbd5e1"/>')
            for i, line in enumerate(b["footer"]):
                body.append(f'<text x="{_num(b["x"] + LR_PAD)}" y="{_num(sep + 2 + (i + 0.8) * LR_LINE)}" '
                            f'font-family="Menlo, Consolas, monospace" font-size="12" fill="#1d4ed8" '
                            f'xml:space="preserve">{escape(line)}</text>')
    s0 = box[0]
    body.append(f'<line x1="{_num(s0["x"] - 24)}" y1="{_num(s0["y"] + 12)}" x2="{_num(s0["x"])}" '
                f'y2="{_num(s0["y"] + 12)}" stroke="#475569" stroke-width="1.5" marker-end="url(#arrow)"/>')
    return _svg(x - LR_GAP_X + LR_MARGIN, bottom + LR_MARGIN, title, body, _ARROW)
