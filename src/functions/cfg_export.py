"""Other output formats for Items 1-2 (extra): the FIRST/FOLLOW, LL(1) and SLR(1) tables as CSV or LaTeX, and the
parse tree and the LR(0) automaton as Graphviz DOT or as SVG. The SVG layouts are computed here, so the server
needs no Graphviz installation and the files open in any browser. Pure functions; no Flask here."""
